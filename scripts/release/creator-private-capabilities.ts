// Explicit offline release inventory. This file is not a SQL parser or activation approval.
// Private tables deny direct access even to service_role; writes use reviewed definer RPCs.
const roles = ["public", "anon", "authenticated", "service_role"] as const;
function privateTable(table: string): string[] {
  return [`table:private.${table}`, `rls:private.${table}`,
    ...roles.flatMap(role => ["select", "insert", "update", "delete", "truncate"].map(
      operation => `grant-removed:${role}.private.${table}(${operation})`))];
}
function serviceRpc(signature: string): string[] {
  return [`function:public.${signature.split("(")[0]}`, `grant:service_role.public.${signature}`,
    ...["public", "anon", "authenticated"].map(role => `grant-removed:${role}.public.${signature}`)];
}

